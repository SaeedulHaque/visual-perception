"""Generate the Gazebo world: ground, light, props, the robot and the walking person.

The person's waypoints come from ``ActorPath.waypoints``, the same path the
ground-truth code uses, so the world and the GT cannot drift apart. Props
stand behind the path or beside the robot, never between the camera and the
person, so the person is never occluded.

The robot is part of the world file (the TurtleBot3 Waffle Pi model from
``turtlebot3_gazebo``), so it exists as soon as the world loads: the
simulation can start paused and be unpaused once every node is ready.
"""

from __future__ import annotations

from robust_visual_perception.sim_geometry import ActorPath

WORLD_NAME = "inspection"
ACTOR_NAME = "walker"
ROBOT_NAME = "waffle_pi"
POSE_RATE_HZ = 100
ACTOR_MESH = (
    "https://fuel.gazebosim.org/1.0/Mingfei/models/actor/tip/files/meshes/walk.dae"
)

# (name, x, y, size_x, size_y, size_z, rgb)
PROPS = (
    ("crate_far_left", 14.0, 5.0, 1.2, 1.2, 1.0, "0.55 0.40 0.25"),
    ("crate_far_right", 14.0, -4.0, 1.0, 2.0, 1.4, "0.35 0.45 0.55"),
    ("shelf_left", 1.5, 7.0, 3.0, 0.5, 1.8, "0.50 0.50 0.45"),
    ("pillar_right", 1.0, -7.0, 0.6, 0.6, 3.0, "0.60 0.60 0.60"),
)

_SYSTEMS = (
    ("gz-sim-physics-system", "gz::sim::systems::Physics", ""),
    ("gz-sim-user-commands-system", "gz::sim::systems::UserCommands", ""),
    ("gz-sim-scene-broadcaster-system", "gz::sim::systems::SceneBroadcaster", ""),
    (
        "gz-sim-sensors-system",
        "gz::sim::systems::Sensors",
        "<render_engine>ogre2</render_engine>",
    ),
    ("gz-sim-imu-system", "gz::sim::systems::Imu", ""),
)


def _box(name: str, x: float, y: float, sx: float, sy: float, sz: float, rgb: str):
    size = f"{sx} {sy} {sz}"
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {sz / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{size}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{size}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


def world_sdf(
    path: ActorPath,
    waypoint_dt: float,
    robot_pose: tuple[float, float, float] = (0.0, 0.0, 0.0),
) -> str:
    """World SDF; ``robot_pose`` is the robot's start (x, y, yaw)."""
    rx, ry, ryaw = robot_pose
    systems = "".join(
        f'    <plugin filename="{f}" name="{n}">{body}</plugin>\n'
        for f, n, body in _SYSTEMS
    )
    props = "".join(_box(*p) for p in PROPS)
    waypoints = "".join(
        f"          <waypoint><time>{t:.6f}</time>"
        f"<pose>{x:.6f} {y:.6f} {z:.6f} 0 0 {yaw:.6f}</pose></waypoint>\n"
        for t, x, y, z, yaw in path.waypoints(waypoint_dt)
    )
    return f"""<?xml version="1.0"?>
<!-- Generated by scripts/make_sim_world.py from configs/sim/world.yaml. Do not edit. -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics name="1ms" type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>
{systems}    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.75 0.80 0.85 1</background>
      <shadows>false</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.85 0.85 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
          <material><ambient>0.45 0.45 0.45 1</ambient><diffuse>0.55 0.55 0.55 1</diffuse></material>
        </visual>
      </link>
    </model>
{props}    <include>
      <uri>model://turtlebot3_waffle_pi</uri>
      <name>{ROBOT_NAME}</name>
      <pose>{rx} {ry} 0.01 0 0 {ryaw}</pose>
      <!-- True model pose in the world, stamped with sim time, on
           /model/{ROBOT_NAME}/pose: the ground-truth robot pose. -->
      <plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher">
        <publish_model_pose>true</publish_model_pose>
        <publish_link_pose>false</publish_link_pose>
        <publish_visual_pose>false</publish_visual_pose>
        <publish_collision_pose>false</publish_collision_pose>
        <publish_sensor_pose>false</publish_sensor_pose>
        <publish_nested_model_pose>false</publish_nested_model_pose>
        <use_pose_vector_msg>false</use_pose_vector_msg>
        <update_frequency>{POSE_RATE_HZ}</update_frequency>
      </plugin>
    </include>
    <actor name="{ACTOR_NAME}">
      <skin><filename>{ACTOR_MESH}</filename><scale>1.0</scale></skin>
      <animation name="walking">
        <filename>{ACTOR_MESH}</filename>
        <scale>1.0</scale>
        <interpolate_x>true</interpolate_x>
      </animation>
      <script>
        <loop>true</loop>
        <auto_start>true</auto_start>
        <trajectory id="0" type="walking">
{waypoints}        </trajectory>
      </script>
    </actor>
  </world>
</sdf>
"""
